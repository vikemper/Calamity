using Content.Client.UserInterface.Controls;
using Content.Shared._Calamity.Ships;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Calamity.Ships.UI;

[GenerateTypedNameReferences]
public sealed partial class CalamityPersonalShipConsoleWindow : FancyWindow
{
    public event Action<CalamityPersonalShipConsoleAction, NetEntity?>? ActionRequested;
    private NetEntity? _selectedShip;

    public CalamityPersonalShipConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        StoreButton.OnPressed += _ => ActionRequested?.Invoke(CalamityPersonalShipConsoleAction.Store, null);
        RetrieveButton.OnPressed += _ => ActionRequested?.Invoke(CalamityPersonalShipConsoleAction.Retrieve, null);
        UnlinkButton.OnPressed += _ => ActionRequested?.Invoke(CalamityPersonalShipConsoleAction.Unlink, null);
        LinkButton.OnPressed += _ =>
        {
            if (_selectedShip is { } ship)
                ActionRequested?.Invoke(CalamityPersonalShipConsoleAction.Link, ship);
        };
        RefreshButton.OnPressed += _ => ActionRequested?.Invoke(CalamityPersonalShipConsoleAction.Refresh, null);
    }

    public void UpdateState(CalamityPersonalShipConsoleState state)
    {
        CharacterLabel.Text = Loc.GetString("calamity-personal-ship-console-character", ("name", state.CharacterName));
        IdLabel.Text = Loc.GetString("calamity-personal-ship-console-id", ("name", state.IdName));
        StoreButton.Disabled = !state.CanStore;
        StoreStatus.Visible = state.StoreUnavailableReason != null;
        StoreStatus.Text = state.StoreUnavailableReason ?? string.Empty;
        RetrieveButton.Disabled = !state.CanRetrieve;
        UnlinkButton.Disabled = !state.CanUnlink;

        ShipDetails.DisposeAllChildren();
        if (state.LinkedShipName is { } linkedName)
        {
            ShipDetails.AddChild(new Label
            {
                Text = Loc.GetString("calamity-personal-ship-console-linked", ("name", linkedName)),
            });
        }
        else if (state.StoredShipName is { } storedName)
        {
            ShipDetails.AddChild(new Label
            {
                Text = Loc.GetString("calamity-personal-ship-console-stored", ("name", storedName)),
            });
        }
        else
        {
            ShipDetails.AddChild(new Label
            {
                Text = Loc.GetString("calamity-personal-ship-console-empty"),
            });
        }

        DockedShips.DisposeAllChildren();
        _selectedShip = null;
        LinkButton.Disabled = true;
        foreach (var ship in state.DockedShips)
        {
            var button = new Button
            {
                Text = ship.Name,
                ToggleMode = true,
                HorizontalExpand = true,
                Disabled = !ship.CanLink,
            };
            button.OnPressed += _ =>
            {
                foreach (var child in DockedShips.Children)
                {
                    if (child is Button candidate && candidate != button)
                        candidate.Pressed = false;
                }

                _selectedShip = ship.CanLink ? ship.Ship : null;
                LinkButton.Disabled = _selectedShip == null;
            };
            DockedShips.AddChild(button);
        }
    }
}
